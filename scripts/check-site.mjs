import assert from 'node:assert/strict';
import { readFile, access } from 'node:fs/promises';
import { steps } from '../src/data.js';
const html = await readFile('dist/index.html','utf8');
assert.equal((html.match(/<h1[ >]/g)||[]).length,1,'Exactly one H1');
const ids = new Set([...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]));
for(const [,id] of html.matchAll(/href="#([^"]+)"/g)) assert.ok(ids.has(id),`Missing anchor ${id}`);
for(const [,src] of html.matchAll(/\b(?:src|data-src)="(\/[^\"]+)"/g)) await access(`dist${src}`);
for(const step of steps) assert.ok(html.includes(step.text),'Every treatment explanation must be present in static HTML');
const json = html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1];
const schema = JSON.parse(json);
assert.equal(schema['@type'],'Dentist');
assert.equal(schema.telephone,'+916201049711');
assert.equal(schema.address.postalCode,'811202');
assert.equal(schema.openingHoursSpecification[0].dayOfWeek.length,7);
assert.ok(!schema.aggregateRating && !schema.geo,'No invented review score or location coordinates');
const canonical = html.match(/rel="canonical" href="([^"]+)"/)[1];
assert.ok((await readFile('dist/sitemap.xml','utf8')).includes(canonical));
assert.ok((await readFile('dist/robots.txt','utf8')).includes('/sitemap.xml'));
assert.ok(!html.includes('9101/A'),'Unverified registration is omitted');
const hero = html.match(/<section class="hero"[\s\S]*?<\/section>/)[0];
assert.match(hero, /Your Dentist<br\s*\/?>(?:\s*)in Munger/, 'Local search intent in H1');
for (const detail of ['Dr. Rohan Bharti', 'BDS', 'Mogal Bazar', '10:30 AM', 'tel:+916201049711', 'google.com/maps/search/']) assert.ok(hero.includes(detail), `Hero must show ${detail}`);
assert.equal(schema.employee.name, 'Dr. Rohan Bharti');
assert.equal(schema.employee.hasCredential.name, 'Bachelor of Dental Surgery (BDS)');
assert.ok(html.includes('<strong>Dr. Rohan Bharti</strong><span>BDS · Dental Surgeon</span>'), 'Doctor caption identifies qualification and role');
assert.ok(!html.includes('Background digitally edited'), 'Internal photo editing note is absent');
assert.ok(!html.includes('/images/preview-dentist.webp') && !html.includes('/images/preview-treatment-room.webp'),'Supplied clinic images replace generated placeholders');
assert.ok(html.includes('/images/whatsapp-mark.svg'),'Official-source WhatsApp artwork is used');
assert.equal((html.match(/<form\b/g)||[]).length,1,'One appointment form');
assert.equal((html.match(/id="appointment"/g)||[]).length,1,'One shared appointment destination');
assert.ok(ids.has('planner'),'Old planner deep link remains available');
assert.ok(!html.includes('Plan your smile journey') && !html.includes('name="service"') && !html.includes('name="time"'),'Long planner and booking questions removed');
for(const control of ['day-today','day-tomorrow','day-custom','patient-name','date']) assert.ok(ids.has(control),`Quick booking control ${control}`);
console.log('Static checks passed: headings, navigation, image files, five indexable treatment steps, schema and SEO outputs.');
